"""Autotools (configure.ac, Makefile.am, Makefile.in) rewriting.

Flags are translated where they are written by hand: configure.ac (m4 around
shell) and Makefile.am / Makefile.in (`AM_LDFLAGS`, `foo_LDFLAGS`). The
generated `configure` and libtool's `ltmain.sh` are left alone -- they are full
of case patterns such as `-fuse-ld=*)` whose rewriting would break the shell.

eld is selected at configure time, the way autotools expects linker choices to
be made: `configure LDFLAGS="-B<shim>/ ..."`. configure records LDFLAGS into
every generated Makefile and libtool passes `-B*` through to the compiler
driver for executables and shared libraries alike.
"""
from __future__ import annotations

from typing import List, Tuple

from ..mapping import Diag
from ..rewrite import Rewriter
from .make import rewrite_make_text

AUTOCONF_NAMES = ("configure.ac", "configure.in")
AUTOMAKE_SUFFIXES = (".am", ".in")


def rewrite_configure_ac(text: str, linker: str, file: str = "configure.ac") -> Tuple[str, List[Diag]]:
    rw = Rewriter(linker, shell=True, continuations=True)
    return rw.rewrite_text(text, file), rw.diags


def rewrite_automake(text: str, linker: str, file: str = "Makefile.am") -> Tuple[str, List[Diag]]:
    # configure supplies the selection; nothing to include.
    return rewrite_make_text(text, linker, file, add_include=False, shell=True)


# libtool forwards only a fixed list of compiler flags when it links a shared
# library, and `-B*` is not on it (libtool 2.4.7), so the eld selection in
# LDFLAGS would reach programs but silently not libraries. Adding `-B*` to that
# pass-through case pattern fixes it; the anchor `|-q*|-m*|` has been there since
# libtool 1.5.
LIBTOOL_ANCHOR = "|-q*|-m*|"
LIBTOOL_PATCHED = "|-q*|-m*|-B*|"
LIBTOOL_SED = r"s/|-q\*|-m\*|\(-B\*|\)\{0,1\}/|-q*|-m*|-B*|/"
# Shell snippet: patch every generated libtool script under the current directory.
PATCH_LIBTOOL_SH = (
    "for lt in $(find . -maxdepth 3 -name libtool -type f 2>/dev/null); do "
    "grep -q 'func_mode_link' \"$lt\" && sed -i '" + LIBTOOL_SED + "' \"$lt\"; done; true")


def patch_libtool_text(text: str) -> str:
    """ltmain.sh / libtool: let `-B<dir>` through to shared-library links."""
    if LIBTOOL_PATCHED in text or LIBTOOL_ANCHOR not in text or "func_mode_link" not in text:
        return text
    return text.replace(LIBTOOL_ANCHOR, LIBTOOL_PATCHED, 1)


BUILD_SH_AUTOTOOLS = """#!/bin/sh
# Generated by eldconv -- configure & build an Autotools tree with eld.
# Extra arguments go to configure (e.g. --host=aarch64-linux-gnu).
set -eu
SRC="$(cd "$(dirname "$0")" && pwd)"
# Configured in the source tree, which every autotools project supports
# (out-of-tree "VPATH" builds are optional), exactly as `eldconv check` does.
ELD="${ELDCONV_ELD:-@ELD@}"
export ELDCONV_ELD="$ELD"
# GCC and Clang look for `ld` in COMPILER_PATH too: this reaches every link,
# including ones libtool or a sub-make assemble without LDFLAGS.
export COMPILER_PATH="$SRC/@SHIM@${COMPILER_PATH:+:$COMPILER_PATH}"
cd "$SRC"
if [ ! -x ./configure ]; then
  autoreconf -fi
fi
./configure LDFLAGS="-B$SRC/@SHIM@/@NOPLUGIN@ ${LDFLAGS:-}" @FATLTO@"$@"
# let libtool pass -B<shim> through to shared-library links too
@PATCH@
make -j"${JOBS:-$(nproc 2>/dev/null || echo 4)}"
"""
