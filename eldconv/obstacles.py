"""Detect build-level obstacles that no flag translation can fix.

Some projects gate on the *identity* of the linker rather than on the flags it
accepts: they run `$(LD) --version` and refuse to proceed unless the output
matches a known linker. Converting the flags perfectly still leaves such a
build dead at configure time, so eldconv reports these up front with the file,
the line and what the user has to do about it.
"""
from __future__ import annotations

import fnmatch
import os
import re
from pathlib import Path
from typing import List, Optional

from .mapping import Diag

# (id, filename glob, pattern, message)
CHECKS = [
    (
        "kbuild-ld-version",
        ("ld-version.sh",),
        re.compile(r'"\$1"\s*=\s*GNU|"\$1"\s*=\s*LLD|\[\s*"\$1"\s*!=\s*"LLD"'),
        "kbuild only accepts a linker whose `--version` output identifies it as "
        "'GNU ld' or 'LLD' (this is why mold cannot build the kernel). eld 24.0 "
        "PASSES this gate unmodified -- it reports 'GNU ld compatible linker - eld "
        "24.0', which kbuild reads as BFD 24.0 -- so this is informational for eld. "
        "Check it if you use a linker, or an eld build, whose version string differs.",
    ),
    (
        "kbuild-ld-name",
        ("Kconfig.include", "Makefile", "Makefile.*", "*.mk"),
        re.compile(r"\$\(error-if,\$\(success,test -z \"\$\(ld-info\)\"\)|"
                   r"\bld-name\s*:?=|CONFIG_LD_IS_(?:BFD|LLD)\b"),
        "the build branches on which linker it thinks it is using (ld-name / "
        "CONFIG_LD_IS_BFD / CONFIG_LD_IS_LLD). eld will fall into whichever "
        "branch the identity check selects; review those paths after converting.",
    ),
    (
        "configure-linker-probe",
        ("configure", "configure.ac", "meson.build"),
        re.compile(r"GNU ld|gold|\bLLD\b|ld --version|linker_version"),
        "the configure script probes the linker's identity or version; a build "
        "generated by it may reject eld regardless of the flags used.",
    ),
]

SKIP_PARTS = {".git", "__pycache__", "eld-bin"}

# Places a linker is chosen that are not build files eldconv rewrites: CI
# configs, wrapper scripts, container recipes. Converting the build files does
# nothing about these, so they are reported for the user to change by hand.
OUTSIDE_GLOBS = ("*.sh", "*.bash", "Dockerfile", "Dockerfile.*", "*.dockerfile", "*.yml", "*.yaml",
                 "Jenkinsfile", ".bazelrc", "*.bazelrc", "*.ini", "*.toml", "*.env", ".envrc")
OUTSIDE_RE = re.compile(
    r"-fuse-ld=(?:bfd|lld|gold|mold)\b|--ld-path=\S*(?:lld|gold|mold)|\bCMAKE_LINKER_TYPE[=:]\s*\"?(?:LLD|GOLD|MOLD|BFD)"
    r"|\b(?:CC|CXX|C|CPP)_LD\s*=\s*\S*(?:lld|gold|mold|bfd)|^\s*c(?:pp)?_ld\s*=|\bmold\s+-run\b"
    r"|(?:^|\s)(?:export\s+)?LD=\S*ld\.(?:lld|gold|bfd)|-B\s*\S*libexec/mold", re.I | re.M)
OUTSIDE_SKIP = ("meson.build", "meson_options.txt", "meson.options")
# Every OUTSIDE_RE alternative contains one of these (case-insensitively). Checking for them
# first is ~10x cheaper than running OUTSIDE_RE over every script and YAML file in a big tree.
OUTSIDE_HINTS = ("fuse-ld", "ld-path", "linker_type", "_ld", "mold", "ld=")
_OUTSIDE_GLOB_RE = re.compile("|".join(fnmatch.translate(g) for g in OUTSIDE_GLOBS))

# eld before late September 2026 has no i386 (32-bit x86) emulation: such a link fails outright.
I386_RE = re.compile(r"(?<![\w-])-m\s*elf_i386\b|(?<![\w-])-melf_i386\b|\bARCH\s*[:?]?=\s*i[3-6]86\b"
                     r"|CMAKE_SYSTEM_PROCESSOR\s+\"?i[3-6]86\b|--target=i[3-6]86-")


def _walk_outside(root: Path) -> List[Path]:
    """One pass over the tree (a per-glob rglob is ~15 full walks of the kernel)."""
    found: List[Path] = []
    for d, dirs, files in os.walk(root):
        dirs[:] = sorted(x for x in dirs if x not in SKIP_PARTS and x not in (".hg", ".svn", "node_modules"))
        for f in sorted(files):
            if f in OUTSIDE_SKIP:
                continue
            if _OUTSIDE_GLOB_RE.match(f):
                found.append(Path(d) / f)
    return found


def _scan_outside(root: Path) -> List[Diag]:
    diags: List[Diag] = []
    for p in _walk_outside(root):
        try:
            if not p.is_file() or p.stat().st_size > (1 << 20):
                continue
            text = p.read_text(errors="replace")
        except OSError:
            continue
        low = text.lower()
        if not any(h in low for h in OUTSIDE_HINTS):
            continue
        for m in OUTSIDE_RE.finditer(text):
            lead = len(m.group(0)) - len(m.group(0).lstrip())
            line = text.count("\n", 0, m.start() + lead) + 1
            diags.append(Diag("warn", m.group(0).strip(),
                              "linker chosen outside the build files (script, CI or container "
                              "config); the conversion does not change this -- update it by hand "
                              "or the build will not link with eld", str(p.relative_to(root)), line))
    return diags


def _scan_i386(root: Path, build_files: Optional[List[Path]] = None) -> List[Diag]:
    from .detect import iter_build_files
    for p in (build_files if build_files is not None else iter_build_files(root)):
        try:
            text = p.read_text(errors="replace")
        except OSError:
            continue
        m = I386_RE.search(text)
        if m:
            line = text.count("\n", 0, m.start()) + 1
            from .surface import active
            surf = active()
            where = (str(p.relative_to(root)), line)
            if (root / "arch" / "x86" / "realmode").is_dir() and (root / "Kbuild").exists():
                # a Linux kernel tree: it always carries arch/x86, whatever ARCH is built, so
                # say "if", and point at the realmode Makefile rather than the first hit
                rm = root / "arch" / "x86" / "realmode" / "rm" / "Makefile"
                try:
                    rtext = rm.read_text(errors="replace")
                    hit = I386_RE.search(rtext)
                    where = (str(rm.relative_to(root)), rtext.count("\n", 0, hit.start()) + 1 if hit else 1)
                except OSError:
                    pass
                return [Diag("warn", "ARCH=x86",
                             "Linux kernel: if you build it for x86 (ARCH=x86/x86_64/i386), eld links the "
                             "i386 parts (vDSO, realmode) only in builds from late September 2026 on, and "
                             "eld main of 13 Oct 2026 still stops at vmlinux with \"Fatal: Ignoring physical "
                             "address for section .rodata which is already part of PHDR text\". arm64, arm "
                             "and riscv kernels link.", *where)]
            if surf is not None and "i386" in surf.targets:
                return [Diag("info", m.group(0).strip(),
                             "32-bit x86 target found: the eld this conversion assumes has an i386 backend "
                             "(added late September 2026), but older eld builds have none (\"Emulation failed "
                             "for target : i386\"). Make sure the ld.eld you build with is recent enough.",
                             *where)]
            return [Diag("warn", m.group(0).strip(),
                         "32-bit x86 target found: if this build links for i386, this eld cannot -- it has no "
                         "i386 emulation (\"Emulation failed for target : i386\"). x86_64 kernels are affected "
                         "too: their realmode trampoline is always i386.", *where)]
    return []


KASLR_RE = re.compile(r"^config RANDOMIZE_BASE\b", re.M)


def _scan_kaslr(root: Path) -> List[Diag]:
    """An arm64 kernel with KASLR links with eld but cannot boot (see checker.empty_relocation_bounds)."""
    kconfig = root / "arch" / "arm64" / "Kconfig"
    if not (root / "Kbuild").exists():
        return []
    try:
        text = kconfig.read_text(errors="replace")
    except OSError:
        return []
    m = KASLR_RE.search(text)
    if not m:
        return []
    return [Diag("warn", "CONFIG_RANDOMIZE_BASE",
                 "Linux kernel: if you build it for arm64 with KASLR (CONFIG_RANDOMIZE_BASE, on in defconfig), "
                 "it links but does not boot. eld (main of 20 Oct 2026) sets the linker-script symbols around "
                 ".rela.dyn (__pi_rela_start/__pi_rela_end) as if the section were empty, so the kernel "
                 "applies none of its relocations and crashes before printing anything once KASLR moves it. "
                 "Build with `scripts/config --disable RANDOMIZE_BASE`; CONFIG_RELOCATABLE alone boots. "
                 "`eldconv check` verifies the linked vmlinux.",
                 str(kconfig.relative_to(root)), text.count("\n", 0, m.start()) + 1)]


def scan(root: Path, build_files: Optional[List[Path]] = None) -> List[Diag]:
    """Scan a source tree for linker-identity gates.

    Only files matching a check's own globs are opened, so this stays cheap on
    a tree the size of the kernel (a blanket walk both took seconds and, with
    any file cap, missed late-sorting paths such as scripts/ld-version.sh).
    """
    diags: List[Diag] = []
    for check_id, globs, rx, msg in CHECKS:
        hit = None
        for g in globs:
            for p in sorted(root.rglob(g)):
                if not p.is_file() or any(part in SKIP_PARTS for part in p.parts):
                    continue
                try:
                    text = p.read_text(errors="replace")
                except OSError:
                    continue
                m = rx.search(text)
                if m:
                    hit = (p, text.count("\n", 0, m.start()) + 1)
                    break
            if hit:
                break
        if hit:
            p, line = hit
            diags.append(Diag("error", check_id, msg, str(p.relative_to(root)), line))
    diags.extend(_scan_i386(root, build_files))
    diags.extend(_scan_kaslr(root))
    diags.extend(_scan_outside(root))
    return diags
