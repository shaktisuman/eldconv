LTO_RE = re.compile(r"(?<![\w-])-flto\b|INTERPROCEDURAL_OPTIMIZATION\s*\(?\s*(?:ON|TRUE|1|YES)\b"
                    r"|\bb_lto\s*[=:]\s*['\"]?true|CHECK_IPO_SUPPORTED", re.I)


def _uses_lto(files: List[Path]) -> bool:
    for f in files:
        try:
            if LTO_RE.search(f.read_text(errors="replace")):
                return True
        except OSError:
            continue
    return False


@dataclass
class ConversionReport:
    source: str
    dest: str
    eld: str
    build: dict
    files_rewritten: List[str] = field(default_factory=list)
    diagnostics: List[Diag] = field(default_factory=list)
    generated: List[str] = field(default_factory=list)
    version: str = __version__

    @property
    def errors(self) -> List[Diag]:
        return [d for d in self.diagnostics if d.level == "error"]

    @property
    def warnings(self) -> List[Diag]:
        return [d for d in self.diagnostics if d.level == "warn"]

    def as_dict(self) -> dict:
        return {"version": self.version, "source": self.source, "dest": self.dest, "eld": self.eld,
                "build": self.build, "files_rewritten": self.files_rewritten,
                "generated": self.generated,
                "diagnostics": [d.as_dict() for d in self.diagnostics],
                "summary": {"errors": len(self.errors), "warnings": len(self.warnings),
                            "info": len([d for d in self.diagnostics if d.level == "info"])}}

    def markdown(self) -> str:
        lines = ["# eldconv report", "",
                 f"- source: `{self.source}`", f"- dest: `{self.dest}`", f"- eld: `{self.eld}`",
                 f"- build system: {self.build.get('system')} / toolchain: {self.build.get('toolchain')}"
                 f" / source linker: {self.build.get('linker')}"
                 f"{' (assumed)' if self.build.get('linker_assumed') else ''}", "",
                 f"**{len(self.errors)} errors, {len(self.warnings)} warnings**", ""]
        if self.files_rewritten:
            lines += ["## Rewritten files"] + [f"- {f}" for f in self.files_rewritten] + [""]
        if self.generated:
            lines += ["## Generated files"] + [f"- {f}" for f in self.generated] + [""]
        if self.diagnostics:
            lines += ["## Diagnostics"]
            for d in self.diagnostics:
                loc = (f"{d.file}:{d.line}: " if d.line else f"{d.file}: ") if d.file else ""
                lines.append(f"- [{d.level}] {loc}`{d.flag}` — {d.message}")
            lines.append("")
        if self.build.get("evidence"):
            lines += ["## Detection evidence"] + [f"- {e}" for e in self.build["evidence"]] + [""]
        return "\n".join(lines)


def read_build_file(p: Path) -> str:
    """Read a build file preserving bytes we cannot decode (latin-1 comments etc.)
    and without translating line endings, so a CRLF file stays CRLF."""
    with open(p, "r", encoding="utf-8", errors="surrogateescape", newline="") as fh:
        return fh.read()


def write_build_file(p: Path, text: str) -> None:
    with open(p, "w", encoding="utf-8", errors="surrogateescape", newline="") as fh:
        fh.write(text)


def _write(path: Path, text: str, executable: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        path.unlink()  # replace the link, never write through it
    path.write_text(text)
    if executable:
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def _copy_tree(src: Path, dst: Path, exclude_build_dirs: bool) -> None:
    def ignore(d, names):
        ign = set()
        for n in names:
            path = Path(d) / n
            if n in (".git", ".hg", ".svn", "__pycache__"):
                ign.add(n)
            elif exclude_build_dirs and n in SKIP_DIRS and path.is_dir():
                if looks_like_build_output(path):
                    ign.add(n)
        return ign
    shutil.copytree(src, dst, ignore=ignore, symlinks=True, dirs_exist_ok=False)


def _check_surface_version(eld: str, report: "ConversionReport", log: Log) -> None:
    """Warn when the eld being targeted is not the one the surface describes."""
    from .surface import active, eld_version
    s = active()
    if s is None:
        report.diagnostics.append(Diag("info", "eld surface",
                                       "disabled: options eld rejects are not filtered out"))
        return
    exe = eld if "/" in eld else shutil.which(eld)
    if not exe or not os.access(exe, os.X_OK):
        return
    have = eld_version(exe)
    if have and s.eld_version and have != s.eld_version:
        msg = (f"converting for `{s.eld_version}`, but {eld} reports `{have}`; regenerate "
               f"the option surface with `eldconv surface --eld {eld} -o surface.json` and "
               f"pass `--eld-surface surface.json`")
        report.diagnostics.append(Diag("warn", "eld version", msg))
        log.warn(msg)


RSP_MAX_BYTES = 1 << 20


def _convert_response_files(src: Path, dst: Path, linker: str, report: "ConversionReport", log: Log) -> None:
    """Convert response files the build files point at, when they are in the tree.

    `-Wl,@opts.rsp` holds raw linker arguments and `@flags.rsp` on a compiler
    line holds driver arguments; both are converted in place in DST. A
    reference that does not resolve to a checked-in file (usually one the
    build generates) stays an error.
    """
    from .rewrite import convert_driver_string, convert_raw_string
    done: dict = {}
    for d in list(report.diagnostics):
        if d.kind not in ("rsp-linker", "rsp-driver") or not d.file:
            continue
        ref = d.flag[1:]
        if "$" in ref or "{" in ref:
            continue   # built from a variable: cannot be resolved statically
        cands = [dst / Path(d.file).parent / ref, dst / ref] if not ref.startswith("/") else []
        target = next((c for c in cands if c.is_file()), None)
        if target is None:
            continue
        try:
            target.resolve().relative_to(dst.resolve())
        except ValueError:
            continue   # never edit outside the converted tree
        key = (target, d.kind)
        if key not in done:
            if target.stat().st_size > RSP_MAX_BYTES:
                continue
            text = read_build_file(target)
            fn = convert_raw_string if d.kind == "rsp-linker" else convert_driver_string
            out_lines, diags = [], []
            for ln in text.splitlines():
                new, dd = fn(ln, linker) if ln.strip() else (ln, [])
                out_lines.append(new)
                rel_t = str(target.relative_to(dst))
                for x in dd:
                    x.file = rel_t
                diags.extend(dd)
            new_text = "\n".join(out_lines) + ("\n" if text.endswith("\n") else "")
            if new_text != text:
                if target.is_symlink():
                    target.unlink()
                write_build_file(target, new_text)
                report.files_rewritten.append(str(target.relative_to(dst)))
            report.diagnostics.extend(diags)
            done[key] = True
            log.info(f"converted response file {target.relative_to(dst)}")
        d.level = "info"
        d.message = f"response file converted in place ({'raw linker' if d.kind == 'rsp-linker' else 'driver'} arguments)"


class ConversionError(ValueError):
    """The request cannot be carried out (bad paths, nothing to convert, ...)."""


# Characters that cannot be embedded in the generated shell shim and makefile.
_UNSAFE_PATH_CHARS = set('"$`\\\n\r\'')


def resolve_eld(eld: str) -> Tuple[str, Optional[str]]:
    """Absolute path for the ld.eld the shim will exec, plus a warning if any.

    A path (anything with a "/") is made absolute; a bare name is looked up on
    PATH. Either may legitimately not exist yet -- a tree can be converted on
    one machine and built on another (ELDCONV_ELD overrides it at build time)
    -- so a miss is a warning, not an error.
    """
    if not eld:
        raise ConversionError("--eld must not be empty")
    bad = _UNSAFE_PATH_CHARS & set(eld)
    if bad:
        raise ConversionError(f"--eld path contains characters the generated shell/make "
                              f"files cannot carry safely: {''.join(sorted(bad))!r}")
    if any(c.isspace() for c in eld):
        raise ConversionError("--eld path contains whitespace, which make cannot handle; "
                              "use a path (or symlink) without spaces")
    if "/" in eld or eld.startswith("~"):
        p = Path(eld).expanduser()
        p = p if p.is_absolute() else (Path.cwd() / p)
        p = Path(os.path.normpath(p))
        if not (p.is_file() and os.access(p, os.X_OK)):
            return str(p), f"{p} is not an executable file yet; links fail until it is (or set ELDCONV_ELD)"
        return str(p), None
    found = shutil.which(eld)
    if found:
        return str(Path(found).absolute()), None
    return eld, (f"`{eld}` is not on PATH here; the shim will look it up on PATH at build "
                 f"time (or set ELDCONV_ELD)")


def _replaceable(dst: Path) -> bool:
    """--force only ever deletes an empty directory or a previous eldconv output."""
    if not dst.is_dir() or dst.is_symlink():
        return False
    try:
        if not any(dst.iterdir()):
            return True
    except OSError:
        return False
    return (dst / REPORT_JSON).is_file()


def convert_project(src: Path, dst: Path, eld: str = "ld.eld", source_linker: Optional[str] = None,
                    original_toolchain: Optional[str] = None, extra_cmake_args: str = "",
                    force: bool = False, log: Log = NULL_LOG,
                    build_system: Optional[str] = None) -> "ConversionReport":
    """Write an eld-linked copy of `src` to `dst`.

    The copy is assembled in a temporary sibling directory and moved into place
    only once it is complete, so a failure (or Ctrl-C) never leaves a
    half-converted tree at `dst`.
    """
    src = Path(src).resolve()
    dst = Path(os.path.abspath(dst))
    dst = Path(os.path.realpath(dst.parent)) / dst.name   # a symlinked parent must not hide src/..
    if not src.is_dir():
        raise ConversionError(f"source {src} is not a directory")
    if any(c.isspace() for c in str(dst)):
        raise ConversionError(f"destination {dst} contains whitespace: the generated build files and "
                              "shim paths cannot be quoted reliably across make/CMake/ninja; "
                              "choose a path without spaces")
    if dst == src or src in dst.parents:
        raise ConversionError(f"destination {dst} must be outside the source tree {src}")
    if dst in src.parents:
        raise ConversionError(f"destination {dst} contains the source tree {src}")
    if dst.exists() or dst.is_symlink():
        if not force:
            raise FileExistsError(f"{dst} exists (use --force to replace)")
        if not _replaceable(dst):
            raise ConversionError(f"refusing to replace {dst}: it is not empty and not a previous "
                                  f"eldconv output (no {REPORT_JSON}); remove it yourself")
    eld_abs, eld_warning = resolve_eld(eld)
    dst.parent.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix=f".{dst.name}.eldconv-", dir=dst.parent))
    try:
        work.rmdir()   # copytree wants to create it
        report = _convert(src, work, dst, eld_abs, source_linker, original_toolchain,
                          extra_cmake_args, log, build_system)
        if eld_warning:
            report.diagnostics.insert(0, Diag("warn", "--eld", eld_warning))
            _write(work / REPORT_JSON, json.dumps(report.as_dict(), indent=2))
            _write(work / REPORT_MD, report.markdown())
        if dst.exists() or dst.is_symlink():
            shutil.rmtree(dst) if dst.is_dir() and not dst.is_symlink() else dst.unlink()
        os.replace(work, dst)
    except BaseException:
        shutil.rmtree(work, ignore_errors=True)
        raise
    return report


def _convert(src: Path, dst: Path, final: Path, eld: str, source_linker: Optional[str],
             original_toolchain: Optional[str], extra_cmake_args: str, log: Log,
             build_system: Optional[str] = None) -> "ConversionReport":
    """The conversion proper. Files are written under `dst`; paths baked into
    the output (the shim location for GN/Ninja) use `final`."""
    info: BuildInfo = detect(src, source_linker, log=log, system=build_system)
    if info.linker == "eld":
        raise ConversionError("project already links with eld")
    if info.system == "unknown":
        raise ConversionError(f"no supported build files (CMake, Make, GN, Ninja, Meson, "
                              f"Autotools) found under {src}")

    log.step(f"copying {src} -> {final}")
    _copy_tree(src, dst, exclude_build_dirs=True)
    log.info("copied tree; excluded VCS and build-output directories")
    report = ConversionReport(str(src), str(final), eld, info.as_dict())
    _check_surface_version(eld, report, log)
    linker = info.linker if info.linker in ("bfd", "lld", "gold", "mold") else "bfd"
    if linker != info.linker:
        log.warn(f"source linker is {info.linker}; converting as bfd")
    log.step(f"rewriting build files (source linker: {linker})")
    noplugin = " -fno-use-linker-plugin" if info.toolchain == "gnu" else ""
    gcc_lto = info.toolchain == "gnu" and _uses_lto(info.files)
    if gcc_lto:
        report.diagnostics.append(Diag(
            "warn", "-flto",
            "GCC LTO: eld cannot load GCC's LTO plugin, so slim LTO objects would link "
            "with no code in them. The converted build compiles fat LTO objects "
            "(-ffat-lto-objects): it links correctly, but without link-time "
            "optimisation. Build with clang for LTO through eld."))
        log.warn("GCC LTO detected: compiling fat LTO objects (no link-time optimisation with eld)")
    # Absolute so it works from any GN out/ directory.
    gn_select = f"-B{final / SHIM_DIR}/{noplugin}"

    need_eld_mk = False
    for f in info.files:
        rel = f.relative_to(src)
        target = dst / rel
        if not target.exists():
            continue
        text = read_build_file(target)
        was_symlink = target.is_symlink()
        kind = classify_file(f)
        if f.suffix == ".json":
            # CMakePresets.json: flags live inside JSON strings, so none of the
            # CMake command rewriting (or empty-argument removal) applies.
            new, diags = rewrite_cmake_presets_text(text, linker, str(rel))
        elif kind == "gn":
            new, diags = rewrite_gn_text(text, linker, str(rel), gn_select)
        elif kind == "ninja":
            # For a GN tree the ninja files are generated, so only the GN source
            # is given the selection; a standalone ninja tree gets it here.
            new, diags = rewrite_ninja_text(
                text, linker, str(rel), "" if info.system == "gn" else gn_select,
                "" if info.system == "gn" else str(final / SHIM_DIR / "ld"))
        elif kind == "cmake":
            if f.name == "CMakeCache.txt":
                new, diags = rewrite_cmake_cache_text(text, linker, str(rel))
            else:
                new, diags = rewrite_cmake_text(text, linker, str(rel))
        elif kind == "meson":
            new, diags = rewrite_meson_text(text, linker, str(rel))
            if info.system == "meson" and f.name == "meson.build":
                new, d2 = inject_selection(new, str(final / SHIM_DIR), str(rel))
                diags += d2
        elif kind == "autoconf":
            new, diags = rewrite_configure_ac(text, linker, str(rel))
        elif kind == "automake":
            new, diags = rewrite_automake(text, linker, str(rel))
        else:
            depth = len(rel.parts) - 1
            mk_rel = ("../" * depth) + MK_FILE
            probe, _ = rewrite_make_text(text, linker, str(rel), mk_rel, add_include=False)
            # Only a Make build gets eld.mk pulled into its entry points; in a
            # CMake/Meson/Autotools tree a stray Makefile is not how it builds,
            # unless it now runs $(ELD_SHIM_LD) itself.
            want = (needs_include(text, probe, depth, f.name) if info.system == "make"
                    else "$(ELD_SHIM_LD)" in probe)
            new, diags = rewrite_make_text(text, linker, str(rel), mk_rel, add_include=want)
            need_eld_mk = need_eld_mk or want
        report.diagnostics.extend(diags)
        for d in diags:
            loc = f"{d.file}:{d.line}: " if d.line else ""
            log.diag(d.level, f"{loc}{d.flag}: {d.message}")
        changed = new != text
        log.file_scanned(str(rel), changed, len(diags))
        if changed:
            if was_symlink:
                target.unlink()  # don't write through into the source tree
            write_build_file(target, new)
            report.files_rewritten.append(str(rel))

    _convert_response_files(src, dst, linker, report, log)

    # build files that were copied but never scanned (they live under a directory
    # detect() skips, e.g. an in-tree build dir) still carry the old linker flags
    scanned = {f.relative_to(src) for f in info.files}
    generated_names = {MK_FILE, TOOLCHAIN_FILE, PROJECT_INCLUDE, REPORT_JSON, REPORT_MD, BUILD_SCRIPT}
    # One walk, not one per file: iter_build_files() is a full tree scan, so calling
    # it inside the loop is quadratic (hours on a tree the size of the kernel).
    copied_build_files = {f.relative_to(dst) for f in iter_build_files(dst, skip_build_dirs=False)}
    for rel in sorted(copied_build_files - scanned):
        if rel.name in generated_names or SHIM_DIR in rel.parts:
            continue
        report.diagnostics.append(Diag("warn", str(rel),
                                       "build file in a skipped directory: copied unchanged, "
                                       "still selects the old linker", str(rel)))

    # gates that no flag translation can fix (linker-identity checks)
    log.step("scanning for linker-identity gates")
    obstacles = scan_obstacles(dst, [dst / r for r in sorted(copied_build_files)])
    for d in obstacles:
        log.diag(d.level, f"{d.file}:{d.line}: {d.flag}: {d.message}")
    if not obstacles:
        log.info("none found")
    report.diagnostics.extend(obstacles)

    # shim
    log.step("generating eld selection")
    log.info(f"shim: {final / SHIM_DIR}/ld -> {eld}")
    shim = dst / SHIM_DIR
    _write(shim / "ld", SHIM_LD.replace("@ELD@", eld), executable=True)
    for alias in ("ld.eld", "ld.bfd", "ld.lld", "ld.gold", "ld.mold", "mold"):
        p = shim / alias
        if not p.exists():
            os.symlink("ld", p)
    report.generated.append(f"{SHIM_DIR}/ld (+ aliases)")

    if info.system == "gn":
        _write(dst / ARGS_GN_FILE, ARGS_GN)
        _write(dst / BUILD_SCRIPT, BUILD_SH_GN.replace("@ELD@", eld)
               .replace("@ARGS@", ARGS_GN_FILE), executable=True)
        report.generated += [ARGS_GN_FILE, BUILD_SCRIPT]
    elif info.system == "ninja":
        # A standalone ninja tree has no configure step: the shim is already in
        # the link rules, so the script just runs ninja.
        ninja_dirs = sorted({str(f.relative_to(src).parent) for f in info.files
                             if f.name == "build.ninja"}) or ["."]
        _write(dst / BUILD_SCRIPT, BUILD_SH_NINJA.replace("@ELD@", eld)
               .replace("@DIR@", ninja_dirs[0]), executable=True)
        report.generated.append(BUILD_SCRIPT)
    elif info.system == "cmake":
        orig_inc = ""
        if original_toolchain:
            orig_inc = f'include("{original_toolchain}")'
        tc = (TOOLCHAIN_CMAKE.replace("@VERSION@", __version__).replace("@ELD@", eld)
              .replace("@SHIM@", SHIM_DIR).replace("@PROJECT_INCLUDE@", PROJECT_INCLUDE)
              .replace("@ORIG_INCLUDE@", orig_inc).replace("@NOPLUGIN@", noplugin)
              .replace("@FATLTO@", "ON" if gcc_lto else "OFF"))
        _write(dst / TOOLCHAIN_FILE, tc)
        _write(dst / PROJECT_INCLUDE, PROJECT_INCLUDE_CMAKE)
        _write(dst / BUILD_SCRIPT, BUILD_SH_CMAKE.replace("@ELD@", eld).replace("@TOOLCHAIN@", TOOLCHAIN_FILE)
               .replace("@EXTRA@", extra_cmake_args), executable=True)
        report.generated += [TOOLCHAIN_FILE, PROJECT_INCLUDE, BUILD_SCRIPT]
    elif info.system == "meson":
        _write(dst / BUILD_SCRIPT, BUILD_SH_MESON.replace("@ELD@", eld), executable=True)
        report.generated.append(BUILD_SCRIPT)
    elif info.system == "autotools":
        fat = ('CFLAGS="${CFLAGS--g -O2} -ffat-lto-objects" '
               'CXXFLAGS="${CXXFLAGS--g -O2} -ffat-lto-objects" ') if gcc_lto else ""
        _write(dst / BUILD_SCRIPT, BUILD_SH_AUTOTOOLS.replace("@ELD@", eld).replace("@SHIM@", SHIM_DIR)
               .replace("@NOPLUGIN@", noplugin).replace("@FATLTO@", fat)
               .replace("@PATCH@", PATCH_LIBTOOL_SH), executable=True)
        report.generated.append(BUILD_SCRIPT)
        # A checked-in ltmain.sh is what configure turns into ./libtool.
        for lt in sorted(dst.rglob("ltmain.sh")):
            if SHIM_DIR in lt.parts or not lt.is_file():
                continue
            text = read_build_file(lt)
            new = patch_libtool_text(text)
            if new != text:
                if lt.is_symlink():
                    lt.unlink()
                write_build_file(lt, new)
                rel = str(lt.relative_to(dst))
                report.files_rewritten.append(rel)
                report.diagnostics.append(Diag("info", "libtool", "lets -B<shim> through to "
                                               "shared-library links", rel))
    else:
        _write(dst / BUILD_SCRIPT, BUILD_SH_MAKE.replace("@ELD@", eld), executable=True)
        report.generated.append(BUILD_SCRIPT)
        need_eld_mk = True
    if need_eld_mk:
        _write(dst / MK_FILE, ELD_MK.replace("@VERSION@", __version__).replace("@ELD@", eld)
               .replace("@SHIM@", SHIM_DIR).replace("@NOPLUGIN@", noplugin)
               .replace("@FATLTO_MK@", FATLTO_MK if gcc_lto else "")
               .replace("@COMPILER_PATH_MK@",
                        COMPILER_PATH_MK_KBUILD if (src / "scripts" / "Kbuild.include").exists()
                        else COMPILER_PATH_MK))
        report.generated.insert(0, MK_FILE)

    for g in report.generated:
        log.info(f"wrote {g}")
    _write(dst / REPORT_JSON, json.dumps(report.as_dict(), indent=2))
    _write(dst / REPORT_MD, report.markdown())
    report.generated += [REPORT_JSON, REPORT_MD]
    log.summary()
    log.step(f"done: {len(report.files_rewritten)} file(s) rewritten, "
             f"{len(report.errors)} error(s), {len(report.warnings)} warning(s)")
    return report


def load_report(dst: Path) -> Optional[dict]:
    p = Path(dst) / REPORT_JSON
    if not p.exists():
        return None
    return json.loads(p.read_text())
